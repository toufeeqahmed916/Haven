-- Haven Phase 1 - core schema
-- Run once in a fresh Supabase project.

create extension if not exists pgcrypto with schema extensions;

create type public.app_role as enum (
  'citizen',
  'control_room_admin',
  'response_team',
  'department_officer',
  'super_admin'
);

create type public.app_language as enum ('en', 'ur', 'sd');
create type public.complaint_track as enum ('safety', 'civic');
create type public.urgency_level as enum ('low', 'medium', 'high', 'critical');
create type public.complaint_status as enum (
  'draft',
  'submitted',
  'under_review',
  'accepted',
  'team_assigned',
  'on_the_way',
  'arrived',
  'closed',
  'rejected',
  'reopened'
);
create type public.attachment_kind as enum ('image', 'video', 'audio', 'other');
create type public.document_kind as enum (
  'complaint_application',
  'evidence_checklist',
  'civic_application',
  'fir_draft',
  'other'
);
create type public.team_kind as enum ('response', 'police_referral', 'medical_referral', 'civic_department');
create type public.team_availability as enum ('available', 'busy', 'offline');
create type public.assignment_status as enum ('assigned', 'accepted', 'on_the_way', 'arrived', 'completed', 'cancelled');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  phone text,
  display_name text,
  role public.app_role not null default 'citizen',
  language public.app_language not null default 'en',
  trust_score smallint not null default 50 check (trust_score between 0 and 100),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index profiles_phone_unique on public.profiles(phone) where phone is not null;

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[a-z0-9_]+$'),
  name_en text not null,
  name_ur text,
  name_sd text,
  track public.complaint_track not null,
  is_active boolean not null default true,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now()
);

create table public.complaints (
  id uuid primary key default gen_random_uuid(),
  case_number bigint generated by default as identity unique,
  user_id uuid not null references public.profiles(id) on delete restrict,
  category_id uuid not null references public.categories(id) on delete restrict,
  track public.complaint_track not null,
  original_language public.app_language not null default 'en',
  original_text text not null check (char_length(btrim(original_text)) between 10 and 10000),
  translated_text text,
  summary text,
  rules_urgency public.urgency_level not null default 'low',
  ai_urgency public.urgency_level,
  final_urgency public.urgency_level not null default 'low',
  urgency_reason text,
  danger_flags text[] not null default '{}',
  needs_human_review boolean not null default true,
  ai_failed boolean not null default false,
  duplicate_score numeric(4,3) check (duplicate_score between 0 and 1),
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  address_text text,
  incident_at timestamptz,
  is_anonymous boolean not null default false,
  status public.complaint_status not null default 'submitted',
  rejection_reason text,
  submitted_at timestamptz not null default now(),
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((latitude is null and longitude is null) or (latitude is not null and longitude is not null)),
  check (status <> 'rejected' or rejection_reason is not null)
);

create index complaints_user_created_idx on public.complaints(user_id, created_at desc);
create index complaints_queue_idx on public.complaints(track, final_urgency desc, submitted_at) where status in ('submitted', 'under_review', 'reopened');
create index complaints_status_idx on public.complaints(status, updated_at desc);

create table public.attachments (
  id uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.complaints(id) on delete cascade,
  uploaded_by uuid not null references public.profiles(id) on delete restrict,
  kind public.attachment_kind not null,
  storage_path text not null unique,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 52428800),
  created_at timestamptz not null default now()
);

create index attachments_complaint_idx on public.attachments(complaint_id, created_at);

create table public.playbooks (
  id uuid primary key default gen_random_uuid(),
  scenario_code text not null check (scenario_code ~ '^[a-z0-9_]+$'),
  language public.app_language not null,
  title text not null,
  right_now text[] not null default '{}',
  next_hour text[] not null default '{}',
  next_24_hours text[] not null default '{}',
  is_approved boolean not null default false,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  version integer not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (scenario_code, language, version),
  check (not is_approved or (reviewed_by is not null and reviewed_at is not null))
);

create table public.legal_entries (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  language public.app_language not null default 'en',
  law_name text not null,
  section_reference text not null,
  plain_summary text not null,
  source_url text not null check (source_url ~ '^https://'),
  jurisdiction text not null default 'Pakistan',
  is_verified boolean not null default false,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (not is_verified or (reviewed_by is not null and reviewed_at is not null))
);

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.complaints(id) on delete cascade,
  kind public.document_kind not null,
  content jsonb not null default '{}'::jsonb,
  storage_path text,
  generated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index documents_complaint_idx on public.documents(complaint_id, created_at desc);

create table public.teams (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  kind public.team_kind not null,
  area text not null,
  contact_phone text,
  availability public.team_availability not null default 'offline',
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  is_demo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (name, area),
  check ((latitude is null and longitude is null) or (latitude is not null and longitude is not null))
);

create table public.team_members (
  team_id uuid not null references public.teams(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (team_id, user_id)
);

create table public.assignments (
  id uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.complaints(id) on delete cascade,
  team_id uuid not null references public.teams(id) on delete restrict,
  assigned_by uuid not null references public.profiles(id) on delete restrict,
  eta_minutes integer check (eta_minutes between 1 and 1440),
  status public.assignment_status not null default 'assigned',
  assigned_at timestamptz not null default now(),
  arrived_at timestamptz,
  completed_at timestamptz,
  notes text
);

create unique index one_open_assignment_per_complaint on public.assignments(complaint_id)
where status not in ('completed', 'cancelled');

create table public.status_updates (
  id bigint generated by default as identity primary key,
  complaint_id uuid not null references public.complaints(id) on delete cascade,
  status public.complaint_status not null,
  note text,
  is_visible_to_citizen boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index status_updates_complaint_idx on public.status_updates(complaint_id, created_at);

create table public.admin_actions (
  id bigint generated by default as identity primary key,
  complaint_id uuid not null references public.complaints(id) on delete cascade,
  admin_id uuid not null references public.profiles(id) on delete restrict,
  action text not null,
  reason text,
  old_values jsonb,
  new_values jsonb,
  created_at timestamptz not null default now()
);

create index admin_actions_complaint_idx on public.admin_actions(complaint_id, created_at desc);

create table public.appeals (
  id uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.complaints(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete restrict,
  reason text not null check (char_length(btrim(reason)) between 10 and 2000),
  status text not null default 'submitted' check (status in ('submitted', 'under_review', 'accepted', 'rejected')),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index one_open_appeal_per_complaint on public.appeals(complaint_id)
where status in ('submitted', 'under_review');

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  target_table text not null,
  target_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index audit_logs_target_idx on public.audit_logs(target_table, target_id, created_at desc);
create index audit_logs_actor_idx on public.audit_logs(actor_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger complaints_set_updated_at before update on public.complaints
for each row execute function public.set_updated_at();
create trigger playbooks_set_updated_at before update on public.playbooks
for each row execute function public.set_updated_at();
create trigger legal_entries_set_updated_at before update on public.legal_entries
for each row execute function public.set_updated_at();
create trigger teams_set_updated_at before update on public.teams
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, phone, display_name, language)
  values (
    new.id,
    new.phone,
    nullif(new.raw_user_meta_data ->> 'display_name', ''),
    case
      when new.raw_user_meta_data ->> 'language' in ('en', 'ur', 'sd')
        then (new.raw_user_meta_data ->> 'language')::public.app_language
      else 'en'::public.app_language
    end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

